func loadBunnyImage() (*ebiten.Image, error) {
	raw, err := base64.StdEncoding.DecodeString(bunnyPNGBase64)
	if err != nil {
		return nil, fmt.Errorf("decode embedded bunny: %w", err)
	}
	img, _, err := image.Decode(bytes.NewReader(raw))
	if err != nil {
		return nil, fmt.Errorf("decode embedded bunny image: %w", err)
	}
	return ebiten.NewImageFromImage(img), nil
}
